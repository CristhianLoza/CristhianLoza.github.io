function applyLanguage(lang) {
  const t = i18n[lang];
  document.documentElement.lang = lang;
  document.title = t.title;
  localStorage.setItem("portfolio-language", lang);

  document.querySelectorAll(".nav nav a").forEach((el, i) => {
    if (t.nav[i]) el.textContent = t.nav[i];
  });

  document.getElementById("nav-cv").innerHTML = t.navCv;
  document.getElementById("hero-cv").textContent = t.downloadCv;
  document.getElementById("hero-eyebrow").textContent = t.heroEyebrow;
  document.querySelector(".hero-copy h1").innerHTML = `${t.heroTitle} <span>${t.heroAccent}</span>`;
  document.querySelector(".hero-copy .lead").textContent = t.heroLead;

  const meta = document.querySelectorAll(".hero-meta span");
  meta[0].innerHTML = `<b>8+</b> ${lang === "en" ? "years of experience" : "años de experiencia"}`;
  meta[1].innerHTML = `<b>.NET</b> ${lang === "en" ? "core specialization" : "especialidad principal"}`;
  meta[2].innerHTML = `<b>Colombia</b> · Bogotá`;

  document.querySelector(".btn.primary").textContent = t.viewProjects;
  document.getElementById("profile-name").textContent = "Cristhian Loza Martínez";
  document.getElementById("profile-role").textContent = t.profileRole;

  ["mini-client","mini-services","mini-data"].forEach((id, i) => {
    document.getElementById(id).textContent = t.mini[[0,2,3][i]];
  });

  document.getElementById("focus-eyebrow").textContent = t.focusEyebrow;
  document.getElementById("focus-title").textContent = t.focusTitle;
  document.querySelectorAll(".focus-card").forEach((card, i) => {
    card.querySelector("h3").textContent = t.focus[i][0];
    card.querySelector("p").textContent = t.focus[i][1];
  });

  document.getElementById("about-eyebrow").textContent = t.aboutEyebrow;
  document.getElementById("about-title").textContent = t.aboutTitle;
  document.querySelectorAll("#about .about-grid p").forEach((p, i) => p.textContent = t.about[i]);

  document.getElementById("experience-eyebrow").textContent = t.experienceEyebrow;
  document.getElementById("experience-title").textContent = t.experienceTitle;
  document.querySelectorAll(".timeline-item").forEach((item, i) => {
    item.querySelector(".muted").textContent = t.experience[i][0];
    item.querySelector("h3").textContent = t.experience[i][1];
    item.querySelector("p:last-child").textContent = t.experience[i][2];
  });

  document.getElementById("stack-eyebrow").textContent = t.stackEyebrow;
  document.getElementById("stack-title").textContent = t.stackTitle;
  document.querySelectorAll(".stack-group h3").forEach((h, i) => h.textContent = t.stackGroups[i][0]);

  document.getElementById("projects-eyebrow").textContent = t.projectsEyebrow;
  document.getElementById("projects-title").textContent = t.projectsTitle;
  document.querySelector("#projects .section-note").textContent = t.projectsNote;
  document.querySelectorAll(".filter").forEach((button, i) => button.textContent = t.filters[i]);

  document.querySelectorAll(".project-card").forEach((card, i) => {
    const p = t.projects[i];
    card.querySelector("h3").textContent = p[0];
    card.querySelector(":scope > p").textContent = p[1];
    card.querySelector(".project-more").firstChild.textContent = p[2] + " ";
    card.querySelector(".project-details strong").textContent = p[3];
    card.querySelector(".project-details > p").textContent = p[4];
  });

  document.getElementById("architecture-eyebrow").textContent = t.architectureEyebrow;
  document.getElementById("architecture-title").textContent = t.architectureTitle;
  document.getElementById("architecture-note").textContent = t.architectureNote;

  const cards = document.querySelectorAll(".architecture-card");
  cards.forEach((card, i) => {
    const a = t.architectures[i];
    const top = card.querySelector(".architecture-type");
    const badge = card.querySelector(".architecture-badge");
    const h3 = card.querySelector("h3");
    const p = card.querySelector(":scope > p");
    if (i === 0) {
      top.textContent = a[0]; badge.textContent = a[1]; h3.textContent = a[2];
      card.querySelectorAll(".flow-node")[0].textContent = a[3];
      card.querySelectorAll(".flow-node")[2].textContent = a[4];
      card.querySelectorAll(".flow-node")[3].textContent = a[5];
      p.textContent = a[6];
    } else if (i === 1) {
      top.textContent = a[0]; badge.textContent = a[1]; h3.textContent = a[2];
      card.querySelectorAll(".flow-node")[0].textContent = a[3];
      card.querySelectorAll(".flow-node")[2].textContent = a[4];
      p.textContent = a[5];
    } else if (i === 2) {
      top.textContent = a[0]; badge.textContent = a[1]; h3.textContent = a[2];
      p.textContent = a[3];
    } else {
      top.textContent = a[0]; badge.textContent = a[1]; h3.textContent = a[2];
      card.querySelectorAll(".flow-node")[0].textContent = a[3];
      card.querySelectorAll(".flow-node")[2].textContent = a[4];
      p.textContent = a[5];
    }
  });

  document.querySelector(".architecture-note span:first-child").textContent = t.architectureStack;
  document.querySelector(".architecture-note span:last-child").textContent = t.architectureStackRest;

  document.getElementById("contact-eyebrow").textContent = t.contactEyebrow;
  document.getElementById("contact-title").textContent = t.contactTitle;
  document.querySelector("#contact > p:not(.eyebrow)").textContent = t.contactText;
  document.querySelector("#contact .contact-primary").textContent = t.downloadCv;
  document.querySelector("footer span:last-child").textContent = t.footer;

  document.querySelectorAll(".lang-btn").forEach(btn => btn.classList.remove("active"));
  document.getElementById(`lang-${lang}`).classList.add("active");
}

document.getElementById("lang-es").addEventListener("click", () => applyLanguage("es"));
document.getElementById("lang-en").addEventListener("click", () => applyLanguage("en"));

document.querySelectorAll(".project-more").forEach(button => {
  button.addEventListener("click", () => {
    const card = button.closest(".project-card");
    card.classList.toggle("open");
    const lang = localStorage.getItem("portfolio-language") || "es";
    const text = i18n[lang].projects[Number(card.id.split("-")[1]) - 1][2];
    button.firstChild.textContent = (card.classList.contains("open")
      ? (lang === "en" ? "Hide approach" : "Ocultar enfoque")
      : text) + " ";
  });
});

document.querySelectorAll(".filter").forEach(filter => {
  filter.addEventListener("click", () => {
    document.querySelectorAll(".filter").forEach(item => item.classList.remove("active"));
    filter.classList.add("active");
    const selected = filter.dataset.filter;
    document.querySelectorAll(".project-card").forEach(card => {
      const show = selected === "all" || card.dataset.category.split(" ").includes(selected);
      card.classList.toggle("hidden", !show);
      if (!show) card.classList.remove("open");
    });
  });
});

document.getElementById("year").textContent = new Date().getFullYear();
applyLanguage(localStorage.getItem("portfolio-language") || "es");
